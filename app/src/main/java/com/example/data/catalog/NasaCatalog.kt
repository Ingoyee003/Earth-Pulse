    fun datasetFor(datasetId: String): DatasetMetadata =
        datasets.first { it.id == datasetId }

    fun variableFor(variableId: String): VariableDefinition =
        variables.first { it.id == variableId }

    fun regionFor(regionId: String): StudyRegion =
        regions.first { it.id == regionId }

    fun createCustomRegion(lat: Double, lon: Double): StudyRegion {
        val clampedLat = lat.coerceIn(-89.5, 89.5)
        val clampedLon = lon.coerceIn(-179.5, 179.5)
        val latDir = if (clampedLat >= 0) "N" else "S"
        val lonDir = if (clampedLon >= 0) "E" else "W"
        val formatted = String.format(
            java.util.Locale.US,
            "%.2f°%s, %.2f°%s",
            kotlin.math.abs(clampedLat),
            latDir,
            kotlin.math.abs(clampedLon),
            lonDir,
        )
        return StudyRegion(
            id = "custom_${String.format(java.util.Locale.US, "%.2f_%.2f", clampedLat, clampedLon)}",
            name = "Custom Location ($formatted)",
            countryOrArea = "Global Coordinate Query",
            regionType = "Single Grid Cell (~0.5° × 0.625°)",
            centroidLat = clampedLat,
            centroidLon = clampedLon,
            bboxMinLat = (clampedLat - 0.25).coerceAtLeast(-90.0),
            bboxMaxLat = (clampedLat + 0.25).coerceAtMost(90.0),
            bboxMinLon = (clampedLon - 0.3125).coerceAtLeast(-180.0),
            bboxMaxLon = (clampedLon + 0.3125).coerceAtMost(180.0),
            areaKm2 = 3025,
            summaryDescription = "User-selected global coordinate queried directly against NASA POWER monthly satellite/reanalysis grid.",
            isCustomPoint = true,
        )
    }
